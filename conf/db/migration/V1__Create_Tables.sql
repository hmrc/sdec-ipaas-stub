CREATE TABLE sdec_staff
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid   VARCHAR(50)  NOT NULL UNIQUE,
    name  VARCHAR(150) NOT NULL,
    email VARCHAR(150) DEFAULT NULL
);

CREATE TABLE sdec_team
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    srs_name      VARCHAR(100) NOT NULL UNIQUE,
    is_task_based BOOLEAN DEFAULT FALSE
);

CREATE TABLE staff_role
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT       NOT NULL,
    team_id  BIGINT       NOT NULL,
    srs_role VARCHAR(100) NOT NULL,
    CONSTRAINT fk_staff_role FOREIGN KEY (staff_id) REFERENCES sdec_staff (id),
    CONSTRAINT fk_team_role FOREIGN KEY (team_id) REFERENCES sdec_team (id),
    CONSTRAINT uq_staff_team UNIQUE (staff_id, team_id)
);

CREATE TABLE sdec_recipient
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internal_id  VARCHAR(50) DEFAULT NULL,
    first_name   VARCHAR(100) NOT NULL,
    last_name    VARCHAR(100) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    phone_number VARCHAR(50) DEFAULT NULL,
    nino         VARCHAR(20)  NOT NULL
);


CREATE TABLE sdec_thread
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(100) NOT NULL UNIQUE,
    status                 VARCHAR(20)  NOT NULL,
    created_by             BIGINT       NOT NULL,
    created_timestamp      TIMESTAMP     DEFAULT NULL,
    last_updated_timestamp TIMESTAMP     DEFAULT NULL,
    thread_expiry_date     DATE          DEFAULT NULL,
    case_reference         VARCHAR(100)  DEFAULT NULL,
    request_items          VARCHAR(100)  DEFAULT NULL,
    recipient_id           BIGINT        DEFAULT NULL,
    email                  VARCHAR(255)  DEFAULT NULL,
    name                   VARCHAR(255),
    nino                   VARCHAR(20)   DEFAULT NULL,
    message                VARCHAR(4000) DEFAULT NULL,
    required_by            DATE          DEFAULT NULL,
    team_id                BIGINT       NOT NULL,
    CONSTRAINT fk_thread_staff FOREIGN KEY (created_by) REFERENCES sdec_staff (id),
    CONSTRAINT fk_thread_recipient FOREIGN KEY (recipient_id) REFERENCES sdec_recipient (id),
    CONSTRAINT fk_thread_team FOREIGN KEY (team_id) REFERENCES sdec_team (id)
);


CREATE TABLE sdec_file_metadata
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT       NOT NULL,
    file_name VARCHAR(250) NOT NULL,
    s3_bucket VARCHAR(250) NOT NULL,
    file_key  VARCHAR(250) NOT NULL,
    file_etag VARCHAR(250) NOT NULL,
    file_size BIGINT       NOT NULL,
    file_type VARCHAR(30)  NOT NULL,
    CONSTRAINT fk_file_thread FOREIGN KEY (thread_id) REFERENCES sdec_thread (id)
);